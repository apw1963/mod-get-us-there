-- Get Us There
-- Dungeon and Raid destination / arrival-choice expansion.
--
-- Adds the curated Dungeon and Raid destination catalog.
-- Adds server-authoritative subordinate arrival choices.
--
-- game_tele_id remains the visible destination identity.
-- Arrival choices never expose arbitrary client coordinates.
--
-- No FOREIGN KEY is intentionally created against AzerothCore-owned data.
-- The module validates GAME_TELE, LFG_DUNGEON, and AREA_TRIGGER references
-- at runtime and ignores/logs invalid rows.

CREATE TABLE IF NOT EXISTS `mod_get_us_there_arrival_choice` (
    `game_tele_id` int unsigned NOT NULL,
    `choice_id` smallint unsigned NOT NULL,
    `arrival_mode` varchar(16) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL,
    `display_label` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL,
    `source_type` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL,
    `source_id` int unsigned NOT NULL,
    `is_default` tinyint unsigned NOT NULL DEFAULT '0',
    `enabled` tinyint unsigned NOT NULL DEFAULT '1',
    PRIMARY KEY (`game_tele_id`,`choice_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='GetUsThere server-authoritative arrival choices';

